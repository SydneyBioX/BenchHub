  }

  dataset_source_id <- if ("datasourceID" %in% names(dataset_tbl)) {
    private_submission_chr(dataset_tbl$datasourceID[[1]])
  } else {
    NA_character_
  }
  evidence_source_ids <- if ("evidenceSourceID" %in% names(evidence_tbl)) {
    unique(stats::na.omit(evidence_tbl$evidenceSourceID))
  } else {
    character(0)
  }

  lines <- c(
    "Submission review summary:",
    paste0("  Dataset rows: ", nrow(dataset_tbl)),
    paste0("  Task rows: ", nrow(task_tbl)),
    paste0("  Evidence rows: ", nrow(evidence_tbl)),
    paste0("  Metric rows: ", nrow(metric_tbl)),
    paste0("  Task-metric rows: ", nrow(task_metric_tbl)),
    paste0("  Dataset source: ", private_submission_chr(dataset_tbl$source[[1]])),
    paste0("  Dataset source ID: ", dataset_source_id),
    paste0("  Task names: ", paste(task_tbl$taskName, collapse = ", ")),
    paste0("  Evidence names: ", paste(evidence_tbl$supportingEvidence, collapse = ", ")),
    paste0("  Metric names: ", paste(metric_tbl$metricName, collapse = ", "))
  )

  if (length(evidence_source_ids) > 0) {
    lines <- c(
      lines,
      paste0("  Evidence source IDs: ", paste(evidence_source_ids, collapse = ", "))
    )
  }

  if (!is.na(gist_url)) {
    lines <- c(lines, paste0("  Metric gist URL: ", gist_url))
  }

  if (!is.null(files)) {
    if (isTRUE(files$dataset$prepared) && !is.na(files$dataset$file)) {
      lines <- c(lines, paste0("  Prepared dataset file: ", files$dataset$file))
    }
    if (isTRUE(files$evidence$prepared) && !is.na(files$evidence$file)) {
      lines <- c(lines, paste0("  Prepared evidence file: ", files$evidence$file))
    }
  }

  cli::cli_inform(lines)
  invisible(NULL)
}

private_find_internal_metric_wrapper <- function(metric_name) {
  ns_exports <- getNamespaceExports("BenchHub")
  metric_exports <- ns_exports[grepl("metric$", ns_exports, ignore.case = TRUE)]

  candidates <- c(
    paste0(metric_name, "Metric"),
    paste0(metric_name, "metric")
  )
  candidates <- unique(candidates)

  for (candidate in candidates) {
    if (candidate %in% metric_exports) {
      return(candidate)
    }
  }

  normalized_target <- tolower(gsub("[^a-z0-9]", "", metric_name))
  normalized_exports <- tolower(gsub("[^a-z0-9]", "", sub("metric$", "", metric_exports, ignore.case = TRUE)))
  match_idx <- which(normalized_exports == normalized_target)

  if (length(match_idx) > 0) {
    return(metric_exports[[match_idx[[1]]]])
  }

  NA_character_
}

private_apply_prepared_files_to_submission <- function(submission, files) {
  if (!is.null(files$figshare$dataset)) {
    submission$Dataset$source[] <- files$figshare$dataset$source
    submission$Dataset$datasourceID[] <- files$figshare$dataset$sourceID
  } else if (!is.null(files$dataset)) {
    submission$Dataset$source[] <- private_submission_chr(files$dataset$source)
    submission$Dataset$datasourceID[] <- private_submission_chr(files$dataset$sourceID)
  }

  if (!is.null(files$figshare$evidence)) {
    submission$DatasetEvidence$evidenceSourceID[] <- files$figshare$evidence$sourceID
  }

  submission
}

private_collect_submission_choice <- function(value, choices, title) {
  if (!is.null(value) && !is.na(value) && nzchar(as.character(value))) {
    private_validate_submission_choice(value, title, choices)
    return(as.character(value))
  }

  if (!interactive()) {
    cli::cli_abort(
      "A value for {.val {title}} is required in non-interactive mode."
    )
  }

  selected <- utils::menu(choices, title = title)
  if (selected == 0) {
    cli::cli_abort("A selection for {.val {title}} is required.")
  }

  choices[[selected]]
}

private_collect_submission_text <- function(
    value = NULL,
    prompt,
    fallback = NULL,
    required = TRUE
) {
  if (!is.null(value)) {
    value_chr <- private_submission_chr(value)
    if (!is.na(value_chr) || !required) {
      return(value_chr)
    }
  }

  fallback_chr <- private_submission_chr(fallback)
  if (!is.na(fallback_chr)) {
    return(fallback_chr)
  }

  if (!interactive()) {
    if (required) {
      cli::cli_abort(
        "A value for {.val {prompt}} is required in non-interactive mode."
      )
    }
    return(NA_character_)
  }

  entered <- readline(paste0(prompt, ": "))
  entered_chr <- private_submission_chr(entered)

  if (required && is.na(entered_chr)) {
    cli::cli_abort("A value for {.val {prompt}} is required.")
  }

  entered_chr
}

private_collect_submission_vector <- function(
    value,
    n,
    arg,
    required = TRUE
) {
  if (is.null(value)) {
    return(rep(NA_character_, n))
  }

  if (length(value) == 1) {
    value <- rep(value, n)
  } else if (length(value) != n) {
    cli::cli_abort(c(
      "Invalid length for {.arg {arg}} defaults.",
      "i" = "Provide either one value or exactly {.val {n}} values."
    ))
  }

  value_chr <- as.character(value)
  if (required && any(is.na(value_chr) | !nzchar(value_chr))) {
    value_chr[is.na(value_chr) | !nzchar(value_chr)] <- NA_character_
  }

  value_chr
}
