#' Build a pre-submit Trio submission bundle
#'
#' This is the higher-level R interface for the new submission workflow. It can
#' prepare dataset/evidence files, prepare metric metadata, build the five-table
#' submission object, and return the payload/JSON for inspection before calling
#' `submitTrioSubmission()`.
#'
#' @param trio A `Trio` object.
#' @param dataset_args Named list passed to `buildDatasetSubmission()`.
#' @param task_args Named list passed to `buildDatasetTaskSubmission()`.
#' @param evidence_task_map Named character vector mapping Trio evidence names
#'   to submission task names.
#' @param prepare_files Logical; if `TRUE`, call `prepareTrioSubmissionFiles()`.
#' @param file_args Named list of additional arguments for
#'   `prepareTrioSubmissionFiles()`, excluding `trio`.
#' @param prepare_metrics Logical; if `TRUE`, call
#'   `prepareTrioSubmissionMetrics()`.
#' @param metric_args Named list of additional arguments for
#'   `prepareTrioSubmissionMetrics()`, excluding `trio`.
#' @param build_payload Logical; if `TRUE`, attach the nested payload structure.
#' @param build_json Logical; if `TRUE`, attach the JSON string.
#'
#' @return A named list containing the built `submission`, plus optional
#'   `files`, `metrics`, `payload`, and `json`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' dataset_args <- list(
#'   dataType = "omics",
#'   dataModality = "transcriptomics",
#'   technology = "RNA-seq",
#'   tissue = "blood",
#'   status = "healthy"
#' )
#' task_args <- list(
#'   taskStage = "prediction",
#'   taskType = "classification",
#'   taskName = "class_prediction"
#' )
#' bundle <- prepareTrioSubmissionBundle(
#'   trio = trio,
#'   dataset_args = dataset_args,
#'   task_args = task_args,
#'   evidence_task_map = c(class_labels = "class_prediction")
#' )
#' names(bundle)
#' @export
prepareTrioSubmissionBundle <- function(
    trio,
    dataset_args,
    task_args,
    evidence_task_map,
    prepare_files = FALSE,
    file_args = list(),
    prepare_metrics = FALSE,
    metric_args = list(),
    build_payload = TRUE,
    build_json = FALSE
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  if (missing(dataset_args) || !is.list(dataset_args)) {
    cli::cli_abort("{.arg dataset_args} must be a named list.")
  }

  if (missing(task_args) || !is.list(task_args)) {
    cli::cli_abort("{.arg task_args} must be a named list.")
  }

  if (missing(evidence_task_map) || is.null(evidence_task_map)) {
    cli::cli_abort(
      "{.arg evidence_task_map} must map Trio evidence names to submission task names."
    )
  }

  files <- NULL
  if (isTRUE(prepare_files)) {
    files <- do.call(
      prepareTrioSubmissionFiles,
      c(list(trio = trio), file_args)
    )
  }

  metrics <- NULL
  if (isTRUE(prepare_metrics)) {
    metrics <- do.call(
      prepareTrioSubmissionMetrics,
      c(list(trio = trio), metric_args)
    )
  }

  submission <- buildTrioSubmission(
    trio = trio,
    dataset_args = dataset_args,
    task_args = task_args,
    evidence_task_map = evidence_task_map
  )

  if (!is.null(files)) {
    submission <- private_apply_prepared_files_to_submission(submission, files)
  }

  if (!is.null(metrics)) {
    submission$Metric <- metrics$Metric
  }

  bundle <- list(
    submission = submission,
    files = files,
    metrics = metrics
  )

  if (isTRUE(build_payload)) {
    bundle$payload <- buildTrioSubmissionPayload(submission)
  }

  if (isTRUE(build_json)) {
    bundle$json <- trioSubmissionToJSON(submission)
  }

  bundle
}

#' Interactively prepare a Trio submission bundle
#'
#' This high-level helper provides a `writeCTD()`-style console workflow for
#' the new five-table submission path. It collects dataset, task, evidence, and
#' metric metadata; optionally prepares local files for upload and verifies a
#' Figshare article; optionally uploads custom metrics to a GitHub gist; and
#' returns all submission tables ready for review before calling
#' `submitTrioSubmission()`.
#'
#' @param trio A `Trio` object.
#' @param n_tasks Optional number of tasks to define. If `NULL`, interactive
#'   sessions prompt for it and non-interactive sessions require it through
#'   `task_defaults` or `n_tasks`.
#' @param dataset_defaults Optional named list passed into
#'   `collectDatasetSubmissionInfo()`.
#' @param task_defaults Optional named list passed into
#'   `collectTaskSubmissionInfo()`.
#' @param evidence_defaults Optional named list passed into
#'   `collectEvidenceSubmissionInfo()`.
#' @param metric_defaults Optional named list passed into
#'   `collectMetricSubmissionInfo()`.
#' @param prepare_files Logical; if `TRUE`, prepare dataset/evidence files or
#'   reuse an existing source.
#' @param file_args Optional named list passed into
#'   `prepareTrioSubmissionFiles()`.
#' @param upload_custom_metrics Logical; if `TRUE`, upload custom metrics to a
#'   GitHub gist.
#' @param githubPat Optional GitHub personal access token. Defaults to the
#'   current `GITHUB_PAT` environment variable.
#' @param gistPublic Logical; whether any created gist should be public.
#' @param review Logical; if `TRUE`, print a compact review summary before
#'   returning.
#' @param submit Logical; if `TRUE`, submit the built payload at the end. If
#'   `NULL`, interactive sessions ask whether to submit after the review step.
#' @param url Optional Google Apps Script endpoint URL used when
#'   `submit = TRUE`.
#' @param submittedBy Optional submitter email or identifier used when
#'   `submit = TRUE`.
#' @param build_payload Logical; if `TRUE`, attach the nested payload object.
#' @param build_json Logical; if `TRUE`, attach the JSON string.
#'
#' @return A named list containing collected arguments, optional prepared file
#'   and metric metadata, the final `submission`, and optional `payload`/`json`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' result <- writeSubmission(
#'   trio = trio,
#'   n_tasks = 1,
#'   dataset_defaults = list(
#'     dataType = "omics",
#'     dataModality = "transcriptomics",
#'     technology = "RNA-seq",
#'     tissue = "blood",
#'     status = "healthy"
#'   ),
#'   task_defaults = list(
#'     taskStage = "prediction",
#'     taskType = "classification",
#'     taskName = "class_prediction"
#'   ),
#'   evidence_defaults = list(
#'     taskName = "class_prediction",
#'     evidenceType = "experimental_ground_truth"
#'   ),
#'   metric_defaults = list(metricType = "label_based"),
#'   prepare_files = FALSE,
#'   build_json = FALSE,
#'   review = FALSE
#' )
#' names(result)
#' @export
writeSubmission <- function(
    trio,
    n_tasks = NULL,
    dataset_defaults = list(),
    task_defaults = list(),
    evidence_defaults = list(),
    metric_defaults = list(),
    prepare_files = TRUE,
    file_args = list(),
    upload_custom_metrics = FALSE,
    githubPat = Sys.getenv("GITHUB_PAT"),
    gistPublic = TRUE,
    review = TRUE,
    submit = NULL,
    url = submission_webapp_url,
    submittedBy = NULL,
    build_payload = TRUE,
    build_json = FALSE
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  if (!is.list(dataset_defaults) ||
      !is.list(task_defaults) ||
      !is.list(evidence_defaults) ||
      !is.list(metric_defaults) ||
      !is.list(file_args)) {
    cli::cli_abort("All defaults and {.arg file_args} inputs must be named lists.")
  }

  githubPat <- private_prepare_write_submission_pat(
    trio = trio,
    upload_custom_metrics = upload_custom_metrics,
    githubPat = githubPat
  )

  dataset_args <- collectDatasetSubmissionInfo(
    trio = trio,
    defaults = dataset_defaults
  )

  task_args <- collectTaskSubmissionInfo(
    trio = trio,
    defaults = task_defaults,
    n_tasks = n_tasks
  )

  evidence_args <- collectEvidenceSubmissionInfo(
    trio = trio,
    task_args = task_args,
    defaults = evidence_defaults
  )

  files <- NULL
  if (isTRUE(prepare_files)) {
    file_args <- private_prepare_write_submission_file_args(
      trio = trio,
      name = dataset_args$name,
      file_args = file_args
    )

    verify_now <- isTRUE(file_args$verifyFigshare)
    figshare_url <- file_args$figshareUrl
    file_args$verifyFigshare <- FALSE
    file_args$figshareUrl <- NULL

    files <- do.call(
      prepareTrioSubmissionFiles,
      c(
        list(
          trio = trio,
          name = dataset_args$name
        ),
        file_args
      )
    )

    private_inform_prepared_submission_files(files)

    if (verify_now) {
      if (interactive() && (is.null(figshare_url) || !nzchar(figshare_url))) {
        figshare_url <- private_collect_submission_text(
          prompt = "Figshare article URL",
          required = TRUE
        )
      }

      files$figshare <- private_verify_submission_figshare(
        trio = trio,
        prepared = files,
        figshareUrl = figshare_url,
        datasetFileName = file_args$datasetFileName,
        evidenceFileName = file_args$evidenceFileName,
        skipMd5Check = isTRUE(file_args$skipMd5Check)
      )
    }
  }

  metric_info <- prepareTrioSubmissionMetrics(
    trio = trio,
    name = dataset_args$name,
    uploadCustom = upload_custom_metrics,
    githubPat = githubPat,
    gistPublic = gistPublic
  )

  metric_args <- collectMetricSubmissionInfo(
    trio = trio,
    defaults = metric_defaults
  )
  metric_info$Metric$metricType <- unname(
    metric_args$metricType[
      match(metric_info$Metric$metricName, metric_args$metricName)
    ]
  )

  dataset_tbl <- do.call(
    buildDatasetSubmission,
    c(list(trio = trio), dataset_args)
  )
  task_tbl <- do.call(
    buildDatasetTaskSubmission,
    c(
      list(
        trio = trio,
        datasetID = dataset_tbl$datasetID[[1]]
      ),
      task_args
    )
  )
  evidence_tbl <- buildDatasetEvidenceSubmission(
    trio = trio,
    datasetTaskID = evidence_args$datasetTaskID,
    evidenceName = evidence_args$evidenceName,
    evidenceType = evidence_args$evidenceType
  )
  evidence_tbl$datasetTaskID[] <- NA_character_
  metric_tbl <- metric_info$Metric
  task_metric_tbl <- collectDatasetTaskMetricSubmission(
    trio = trio,
    evidence_args = evidence_args,
    task_args = task_args
  )
  task_metric_tbl$datasetTaskID[] <- NA_character_
  task_metric_tbl$metricID[] <- NA_character_

  submission <- list(
    Dataset = dataset_tbl,
    DatasetTask = task_tbl,
    DatasetEvidence = evidence_tbl,
    Metric = metric_tbl,
    DatasetTaskMetric = task_metric_tbl,
    submission_links = private_build_submission_links(
      trio = trio,
      task_args = task_args,
      evidence_args = evidence_args,
      metric_tbl = metric_tbl
    )
  )

  if (!is.null(files)) {
    submission <- private_apply_prepared_files_to_submission(submission, files)
  }

  result <- list(
    dataset_args = dataset_args,
    task_args = task_args,
    evidence_args = evidence_args,
    metric_args = metric_args,
    files = files,
    metrics = metric_info,
    submission = submission
  )

  if (isTRUE(review)) {
    private_inform_submission_review(
      submission = submission,
      files = files,
      metric_info = metric_info
    )
  }

  if (isTRUE(build_payload)) {
    result$payload <- buildTrioSubmissionPayload(submission)
  }

  if (isTRUE(build_json)) {
    result$json <- trioSubmissionToJSON(submission)
  }

  if (is.null(submit) && interactive()) {
    submit <- utils::askYesNo("Do you want to submit this bundle now?")
  }

  if (isTRUE(submit)) {
    if (is.null(url) || !nzchar(as.character(url))) {
      if (!interactive()) {
        cli::cli_abort(
          "{.arg url} must be provided when {.arg submit = TRUE} in non-interactive mode."
        )
      }
      url <- private_collect_submission_text(
        prompt = "Google Apps Script URL",
        required = TRUE
      )
    }

    if (is.null(submittedBy) || !nzchar(as.character(submittedBy))) {
      if (!interactive()) {
        cli::cli_abort(
          "{.arg submittedBy} must be provided when {.arg submit = TRUE} in non-interactive mode."
        )
      }
      submittedBy <- private_collect_submission_text(
        prompt = "Submitted by",
        required = TRUE
      )
    }

    result$submit_response <- submitTrioSubmission(
      submission = submission,
      url = url,
      submittedBy = submittedBy,
      submittedType = "Trio"
    )

    if (isTRUE(result$submit_response$ok)) {
      cli::cli_inform("Submission completed successfully.")
    } else {
      cli::cli_inform("Submission request finished, but the response was not marked as successful.")
    }
  }

  result
}

#' Build DatasetTaskMetric submission rows from a Trio object
#'
#' This helper creates one `DatasetTaskMetric` row for each task-metric pairing.
#' It does not upload anything and does not modify the existing writeCTD() path.
#'
#' @param trio A `Trio` object.
#' @param datasetTaskID Task identifier(s) to link metrics to. Defaults to `NA`
#'   generated task IDs when not supplied.
#' @param taskMetrics A named list mapping each `datasetTaskID` to its metric
#'   IDs. If omitted, metrics are inferred from the evidence assigned to each
#'   task via `evidenceTaskID`.
#' @param evidenceTaskID Character vector mapping each Trio evidence entry to a
#'   `datasetTaskID`. Used when `taskMetrics` is not supplied.
#' @param evidenceName Character vector of Trio evidence names corresponding to
#'   `evidenceTaskID`. Defaults to all evidence in `trio`.
#'
#' @return A `data.frame` matching the proposed `DatasetTaskMetric` table
#'   schema. `datasetTaskMetricID` and `metricID` are left as `NA`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' buildDatasetTaskMetricSubmission(
#'   trio,
#'   datasetTaskID = "task_001",
#'   evidenceTaskID = "task_001"
#' )
#' @export
buildDatasetTaskMetricSubmission <- function(
    trio,
    datasetTaskID,
    taskMetrics = NULL,
    evidenceTaskID = NULL,
    evidenceName = names(trio$evidence)
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  datasetTaskID <- unique(private_required_submission_chr_vec(
    datasetTaskID,
    "datasetTaskID"
  ))

  if (length(datasetTaskID) == 0) {
    cli::cli_abort(
      "At least one {.arg datasetTaskID} value must be supplied."
    )
  }

  if (is.null(taskMetrics)) {
    evidence_names <- private_required_submission_chr_vec(
      evidenceName,
      "evidenceName"
    )
    if (!all(evidence_names %in% names(trio$evidence))) {
      cli::cli_abort(c(
        "All {.arg evidenceName} values must exist in the Trio object.",
        "i" = "Available evidence: {.val {names(trio$evidence)}}"
      ))
    }

    evidenceTaskID <- private_recycle_submission_value(
      value = evidenceTaskID,
      n = length(evidence_names),
      arg = "evidenceTaskID"
    )

    taskMetrics <- lapply(datasetTaskID, function(one_task_id) {
      task_evidence <- evidence_names[evidenceTaskID == one_task_id]
      unique(unlist(lapply(task_evidence, trio$getMetrics), use.names = FALSE))
    })
    names(taskMetrics) <- datasetTaskID
  } else {
    if (!is.list(taskMetrics) || is.null(names(taskMetrics))) {
      cli::cli_abort(
        "{.arg taskMetrics} must be a named list keyed by datasetTaskID."
      )
    }
  }

  rows <- lapply(datasetTaskID, function(one_task_id) {
    metric_ids <- taskMetrics[[one_task_id]]

    if (is.null(metric_ids) || length(metric_ids) == 0) {
      return(NULL)
    }

    metric_ids <- unique(private_required_submission_chr_vec(
      metric_ids,
      "metricID"
    ))

    data.frame(
      datasetTaskMetricID = rep(NA_character_, length(metric_ids)),
      datasetTaskID = rep(one_task_id, length(metric_ids)),
      metricID = metric_ids,
      stringsAsFactors = FALSE
    )
  })

  rows <- Filter(Negate(is.null), rows)
  if (length(rows) == 0) {
    return(data.frame(
      datasetTaskMetricID = character(0),
      datasetTaskID = character(0),
      metricID = character(0),
      stringsAsFactors = FALSE
    ))
  }

  do.call(rbind, rows)
}

