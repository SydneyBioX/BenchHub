#' Build a Dataset submission row from a Trio object
#'
#' This helper is the first step in the new submission workflow. It does not
#' upload anything and does not modify the existing writeCTD() path.
#'
#' @param trio A `Trio` object.
#' @param name Dataset name for submission. Defaults to the existing Trio name,
#'   falling back to `trio$dataSourceID` when needed.
#' @param dataType One of `"omics"` or `"clinical"`.
#' @param dataModality One of `"genomics"`, `"transcriptomics"`,
#'   `"epigenomics"`, `"proteomics"`, `"metabolomics"`, `"patient"`,
#'   or `"other"`.
#' @param technology Free-text technology description.
#' @param description Dataset description. Defaults to `trio$description` if
#'   present.
#' @param doi DOI reference for the dataset.
#' @param tissue Free-text tissue label.
#' @param organism Free-text organism label.
#' @param status One of `"healthy"`, `"diseased"`, `"developmental"`,
#'   or `"other"`.
#'
#' @return A one-row `data.frame` matching the proposed `Dataset` table schema.
#'   `datasetID` is left as `NA` because it is expected to be generated by the
#'   submission backend.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' buildDatasetSubmission(
#'   trio,
#'   dataType = "omics",
#'   dataModality = "transcriptomics",
#'   technology = "RNA-seq",
#'   tissue = "blood",
#'   status = "healthy"
#' )
#' @export
buildDatasetSubmission <- function(
    trio,
    name = private_submission_dataset_name(trio),
    dataType,
    dataModality,
    technology,
    description = trio$description,
    doi = NA_character_,
    organism = NA_character_,
    tissue,
    status
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  if (is.null(name) || !nzchar(name)) {
    cli::cli_abort(
      "{.arg name} must be provided when the Trio does not already have a usable name."
    )
  }

  private_validate_submission_choice(
    value = dataType,
    arg = "dataType",
    choices = c("omics", "clinical")
  )
  private_validate_submission_choice(
    value = dataModality,
    arg = "dataModality",
    choices = c(
      "genomics",
      "transcriptomics",
      "epigenomics",
      "proteomics",
      "metabolomics",
      "patient",
      "other"
    )
  )
  private_validate_submission_choice(
    value = status,
    arg = "status",
    choices = c(
      "healthy",
      "diseased",
      "developmental",
      "other"
    )
  )

  if (missing(technology) || is.null(technology) || !nzchar(technology)) {
    cli::cli_abort("{.arg technology} must be a non-empty string.")
  }

  if (missing(tissue) || is.null(tissue) || !nzchar(tissue)) {
    cli::cli_abort("{.arg tissue} must be a non-empty string.")
  }

  if (is.null(description) || !nzchar(description)) {
    cli::cli_abort(
      "{.arg description} must be provided when the Trio does not already have a description."
    )
  }

  numSamples <- private_get_submission_num_samples(trio$data)

  data.frame(
    datasetID = NA_character_,
    name = as.character(name),
    source = private_submission_chr(trio$dataSource),
    datasourceID = private_submission_chr(trio$dataSourceID),
    dataType = as.character(dataType),
    dataModality = as.character(dataModality),
    technology = as.character(technology),
    description = as.character(description),
    doi = private_submission_chr(doi),
    numSamples = numSamples,
    organism = private_submission_chr(organism),
    tissue = as.character(tissue),
    status = as.character(status),
    stringsAsFactors = FALSE
  )
}

#' Collect Dataset submission metadata interactively
#'
#' This helper gathers the dataset-level fields needed for the `Dataset` table.
#' It reuses `Trio` metadata when already available and only prompts for the
#' remaining values in interactive sessions.
#'
#' @param trio A `Trio` object.
#' @param defaults Optional named list of pre-filled values. Any non-`NULL`
#'   value here bypasses the interactive prompt for that field.
#'
#' @return A named list ready to pass as `dataset_args` to
#'   `buildDatasetSubmission()`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' collectDatasetSubmissionInfo(
#'   trio,
#'   defaults = list(
#'     dataType = "omics",
#'     dataModality = "transcriptomics",
#'     technology = "RNA-seq",
#'     tissue = "blood",
#'     status = "healthy"
#'   )
#' )
#' @export
collectDatasetSubmissionInfo <- function(
    trio,
    defaults = list()
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  if (!is.list(defaults)) {
    cli::cli_abort("{.arg defaults} must be a named list.")
  }

  data_type <- private_collect_submission_choice(
    value = defaults$dataType,
    choices = c("omics", "clinical"),
    title = "Please choose data type"
  )
  data_modality <- private_collect_submission_choice(
    value = defaults$dataModality,
    choices = c(
      "genomics",
      "transcriptomics",
      "epigenomics",
      "proteomics",
      "metabolomics",
      "patient",
      "other"
    ),
    title = "Please choose data modality"
  )
  status <- private_collect_submission_choice(
    value = defaults$status,
    choices = c(
      "healthy",
      "diseased",
      "developmental",
      "other"
    ),
    title = "Please choose dataset status"
  )

  list(
    name = private_collect_submission_text(
      value = defaults$name,
      prompt = "Dataset name",
      fallback = private_submission_dataset_name(trio)
    ),
    dataType = data_type,
    dataModality = data_modality,
    technology = private_collect_submission_text(
      value = defaults$technology,
      prompt = "Please describe the technology of this dataset",
      required = TRUE
    ),
    description = private_collect_submission_text(
      value = defaults$description,
      prompt = "Dataset description",
      fallback = trio$description,
      required = TRUE
    ),
    doi = private_collect_submission_text(
      value = defaults$doi,
      prompt = "Please describe the DOI of this dataset",
      required = FALSE
    ),
    organism = private_collect_submission_text(
      value = defaults$organism,
      prompt = "Please describe the Organism of this dataset",
      required = FALSE
    ),
    tissue = private_collect_submission_text(
      value = defaults$tissue,
      prompt = "Please describe the Tissue of this dataset",
      required = TRUE
    ),
    status = status
  )
}

#' Prepare Trio files and download metadata for submission
#'
#' This helper reuses the good parts of the old `writeCTD()` workflow for the
#' new submission path. It can either save dataset/evidence files locally so
#' the user can upload them, or reuse an existing downloadable source already
#' attached to the `Trio`.
#'
#' @param trio A `Trio` object.
#' @param name Dataset name used for generated filenames. Defaults to
#'   `trio$name`.
#' @param outputDir Directory for generated `.rds` files. Defaults to `"."`.
#' @param saveData Logical indicating whether to save `trio$data` to an RDS
#'   file. If `NULL` and interactive, the user is prompted.
#' @param saveEvidence Logical indicating whether to save all supporting
#'   evidence to a single RDS file. If `NULL` and interactive, defaults to
#'   `TRUE`.
#' @param useExistingSource Logical indicating whether to keep using
#'   `trio$dataSource`/`trio$dataSourceID` rather than preparing uploaded files.
#'   If `NULL` and interactive, the user is prompted when an existing source is
#'   available.
#' @param figshareUrl Optional Figshare URL to verify against prepared files.
#' @param datasetFileName Optional dataset filename to match inside the Figshare
#'   article.
#' @param evidenceFileName Optional evidence filename to match inside the
#'   Figshare article.
#' @param verifyFigshare Logical; if `TRUE`, verify the prepared files against
#'   the Figshare article metadata.
#' @param skipMd5Check Logical; if `TRUE`, allow verification without MD5
#'   matching.
#'
#' @return A named list describing the saved files and/or reusable download
#'   sources for dataset and evidence.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' files <- prepareTrioSubmissionFiles(
#'   trio,
#'   outputDir = tempdir(),
#'   saveData = TRUE,
#'   saveEvidence = TRUE,
#'   useExistingSource = FALSE
#' )
#' names(files)
#' @export
prepareTrioSubmissionFiles <- function(
    trio,
    name = trio$name,
    outputDir = ".",
    saveData = NULL,
    saveEvidence = NULL,
    useExistingSource = NULL,
    figshareUrl = NULL,
    datasetFileName = NULL,
    evidenceFileName = NULL,
    verifyFigshare = FALSE,
    skipMd5Check = FALSE
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  if (is.null(name) || !nzchar(name)) {
    cli::cli_abort(
      "{.arg name} must be provided when the Trio does not already have a name."
    )
  }

  if (!dir.exists(outputDir)) {
    cli::cli_abort("{.arg outputDir} must be an existing directory.")
  }

  existing_source_available <- !is.null(trio$dataSource) &&
    nzchar(as.character(trio$dataSource)) &&
    !is.null(trio$dataSourceID) &&
    nzchar(as.character(trio$dataSourceID))

  if (is.null(useExistingSource)) {
    if (interactive() && existing_source_available) {
      useExistingSource <- utils::askYesNo(
        "Use the existing Trio download source instead of preparing a dataset file?"
      )
    } else {
      useExistingSource <- existing_source_available
    }
  }

  if (is.null(saveData)) {
    if (interactive() && !useExistingSource) {
      saveData <- utils::askYesNo(
        "Do you want to save the data to an RDS file in the selected output directory?"
      )
    } else {
      saveData <- !useExistingSource
    }
  }

  if (is.null(saveEvidence)) {
    if (interactive()) {
      saveEvidence <- utils::askYesNo(
        "Do you want to save all supporting evidence to a single RDS file?"
      )
    } else {
      saveEvidence <- TRUE
    }
  }

  result <- list(
    dataset = list(
      name = name,
      source = private_submission_chr(trio$dataSource),
      sourceID = private_submission_chr(trio$dataSourceID),
      file = NA_character_,
      fileName = NA_character_,
      md5 = NA_character_,
      prepared = FALSE
    ),
    evidence = list(
      source = if (length(trio$evidenceSource) > 0) trio$evidenceSource else NULL,
      sourceID = if (length(trio$evidenceSourceID) > 0) trio$evidenceSourceID else NULL,
      file = NA_character_,
      fileName = NA_character_,
      md5 = NA_character_,
      prepared = FALSE
    )
  )

  if (isTRUE(saveData)) {
    dataset_path <- file.path(outputDir, paste0(name, "_dataset.rds"))
    saveRDS(trio$data, file = dataset_path, compress = "xz")

    result$dataset$file <- dataset_path
    result$dataset$fileName <- basename(dataset_path)
    result$dataset$md5 <- unname(tools::md5sum(dataset_path))
    result$dataset$prepared <- TRUE
    result$dataset$source <- NA_character_
    result$dataset$sourceID <- NA_character_
  } else if (!isTRUE(useExistingSource)) {
    cli::cli_abort(c(
      "The dataset must either be saved for upload or already have a downloadable source.",
      "i" = "Set {.arg saveData = TRUE} or provide Trio source metadata."
    ))
  }

  if (isTRUE(saveEvidence)) {
    if (length(trio$evidence) == 0) {
      cli::cli_abort(
        "The Trio object has no supporting evidence, so no evidence file can be prepared."
      )
    }

    evidence_path <- file.path(outputDir, paste0(name, "_evidence.rds"))
    saveRDS(trio$evidence, file = evidence_path, compress = "xz")

    result$evidence$file <- evidence_path
    result$evidence$fileName <- basename(evidence_path)
    result$evidence$md5 <- unname(tools::md5sum(evidence_path))
    result$evidence$prepared <- TRUE
    result$evidence$source <- NA_character_
    result$evidence$sourceID <- NA_character_
  }

  if (isTRUE(verifyFigshare)) {
    result$figshare <- private_verify_submission_figshare(
      trio = trio,
      prepared = result,
      figshareUrl = figshareUrl,
      datasetFileName = datasetFileName,
      evidenceFileName = evidenceFileName,
      skipMd5Check = skipMd5Check
    )
  }

  result
}

#' Build DatasetTask submission rows from a Trio object
#'
#' This helper creates one `DatasetTask` row per supporting evidence name in the
#' Trio object. It does not upload anything and does not modify the existing
#' writeCTD() path.
#'
#' @param trio A `Trio` object.
#' @param datasetID Dataset identifier to link tasks to. Defaults to `NA` so the
#'   backend can fill it later.
#' @param taskStage A character vector giving the task stage for each task row.
#' @param taskType A character vector giving the task type for each task row.
#' @param taskName A character vector giving the task name for each task row.
#'
#' @return A `data.frame` matching the proposed `DatasetTask` table schema.
#'   `datasetTaskID` is left as `NA`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' buildDatasetTaskSubmission(
#'   trio,
#'   taskStage = "prediction",
#'   taskType = "classification",
#'   taskName = "class_prediction"
#' )
#' @export
buildDatasetTaskSubmission <- function(
    trio,
    datasetID = NA_character_,
    taskStage,
    taskType,
    taskName
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  n_tasks <- private_submission_row_count(taskStage, taskType, taskName)
  if (n_tasks < 1) {
    cli::cli_abort("At least one DatasetTask row must be created.")
  }

  if (length(trio$evidence) == 0) {
    cli::cli_abort(c(
      "The Trio object has no supporting evidence.",
      "i" = "Add supporting evidence before building task-linked submission tables."
    ))
  }

  taskStage <- private_recycle_submission_value(
    value = taskStage,
    n = n_tasks,
    arg = "taskStage"
  )
  taskType <- private_recycle_submission_value(
    value = taskType,
    n = n_tasks,
    arg = "taskType"
  )
  taskName <- private_recycle_submission_value(
    value = taskName,
    n = n_tasks,
    arg = "taskName"
  )
  data.frame(
    datasetTaskID = rep(NA_character_, n_tasks),
    datasetID = rep(private_submission_chr(datasetID), n_tasks),
    taskStage = private_required_submission_chr_vec(taskStage, "taskStage"),
    taskType = private_required_submission_chr_vec(taskType, "taskType"),
    taskName = private_required_submission_chr_vec(taskName, "taskName"),
    stringsAsFactors = FALSE
  )
}

#' Collect DatasetTask submission metadata interactively
#'
#' This helper gathers the task-level fields needed for the `DatasetTask`
#' table. It does not modify the `Trio` object.
#'
#' @param trio A `Trio` object.
#' @param defaults Optional named list of pre-filled task values. Supported
#'   entries are `taskStage`, `taskType`, and `taskName`. Each entry may be length 1
#'   or length `n_tasks`.
#' @param n_tasks Number of tasks to define. If `NULL`, interactive sessions
#'   prompt for this value, while non-interactive sessions infer it from the
#'   longest defaults vector.
#'
#' @return A named list ready to pass as `task_args` to
#'   `buildDatasetTaskSubmission()`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' collectTaskSubmissionInfo(
#'   trio,
#'   defaults = list(
#'     taskStage = "prediction",
#'     taskType = "classification",
#'     taskName = "class_prediction"
#'   )
#' )
#' @export
collectTaskSubmissionInfo <- function(
    trio,
    defaults = list(),
    n_tasks = NULL
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  if (!is.list(defaults)) {
    cli::cli_abort("{.arg defaults} must be a named list.")
  }

  if (is.null(n_tasks)) {
    default_lengths <- vapply(
      defaults[c("taskStage", "taskType", "taskName")],
      length,
      integer(1)
    )
    default_lengths <- default_lengths[default_lengths > 0]

    if (interactive()) {
      default_value <- if (length(default_lengths) == 0) "1" else as.character(max(default_lengths))
      entered <- readline(paste0("Number of tasks [", default_value, "]: "))
      entered <- if (nzchar(entered)) entered else default_value
      entered_trimmed <- trimws(entered)
      if (grepl("^[+-]?[0-9]+$", entered_trimmed)) {
        n_tasks <- as.integer(entered_trimmed)
      } else {
        n_tasks <- NA_integer_
      }
    } else if (length(default_lengths) > 0) {
      n_tasks <- max(default_lengths)
    } else {
      cli::cli_abort(
        "{.arg n_tasks} must be provided in non-interactive mode when no task defaults are supplied."
      )
    }
  }

  if (length(n_tasks) != 1 || is.na(n_tasks) || n_tasks < 1) {
    cli::cli_abort("{.arg n_tasks} must be a single positive integer.")
  }
  n_tasks <- as.integer(n_tasks)

  n_evidence <- length(trio$evidence)
  if (n_evidence == 0) {
    cli::cli_abort(
      "The Trio object has no supporting evidence, so no tasks can be collected."
    )
  }

  if (n_tasks > n_evidence) {
    cli::cli_abort(c(
      "The number of tasks cannot exceed the number of supporting evidence items in the Trio.",
      "i" = "This Trio has {.val {n_evidence}} supporting evidence item(s)."
    ))
  }

  task_stage_default <- private_collect_submission_vector(
    value = defaults$taskStage,
    n = n_tasks,
    arg = "taskStage"
  )
  task_type_default <- private_collect_submission_vector(
    value = defaults$taskType,
    n = n_tasks,
    arg = "taskType"
  )
  task_name_default <- private_collect_submission_vector(
    value = defaults$taskName,
    n = n_tasks,
    arg = "taskName"
  )
  task_stage <- character(n_tasks)
  task_type <- character(n_tasks)
  task_name <- character(n_tasks)

  for (i in seq_len(n_tasks)) {
    task_stage[[i]] <- private_collect_submission_task_stage(
      value = task_stage_default[[i]],
      title = paste0("Choose task stage for task ", i)
    )
    task_type[[i]] <- private_collect_submission_task_type(
      value = task_type_default[[i]],
      task_stage = task_stage[[i]],
      title = paste0("Choose task type for task ", i),
      prompt = paste0("Please specify task type for task ", i)
    )
    task_name[[i]] <- private_collect_submission_text(
      value = task_name_default[[i]],
      prompt = paste0("Task name for task ", i),
      required = TRUE
    )
  }

  list(
    taskStage = task_stage,
    taskType = task_type,
    taskName = task_name
  )
}

#' Build DatasetEvidence submission rows from a Trio object
#'
#' This helper creates one `DatasetEvidence` row per supporting evidence entry
#' in the Trio object. It does not upload anything and does not modify the
#' existing writeCTD() path.
#'
#' @param trio A `Trio` object.
#' @param datasetTaskID Task identifier to link evidence rows to. Defaults to
#'   generated task IDs when not supplied.
#' @param evidenceName Character vector of Trio evidence names to include.
#'   Defaults to all evidence in `trio`.
#' @param evidenceType Either \code{"columns"} or \code{"figshare"} indicating
#' where to find the evidence.
#'
#' @return A `data.frame` matching the proposed `DatasetEvidence` table schema.
#'   `evidenceID` is left as `NA`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' buildDatasetEvidenceSubmission(
#'   trio,
#'   datasetTaskID = "task_001",
#'   evidenceType = "experimental_ground_truth"
#' )
#' @export
buildDatasetEvidenceSubmission <- function(
    trio,
    datasetTaskID,
    evidenceName = names(trio$evidence),
    evidenceType = NA_character_
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  evidence_names <- private_required_submission_chr_vec(
    evidenceName,
    "evidenceName"
  )

  if (!all(evidence_names %in% names(trio$evidence))) {
    cli::cli_abort(c(
      "All {.arg evidenceName} values must exist in the Trio object.",
      "i" = "Available evidence: {.val {names(trio$evidence)}}"
    ))
  }

  if (length(evidence_names) == 0) {
    cli::cli_abort(
      "The Trio object has no supporting evidence, so no DatasetEvidence rows can be created."
    )
  }

  n_evidence <- length(evidence_names)
  datasetTaskID <- private_recycle_submission_value(
    value = datasetTaskID,
    n = n_evidence,
    arg = "datasetTaskID"
  )
  evidenceType <- private_recycle_submission_value(
    value = evidenceType,
    n = n_evidence,
    arg = "evidenceType"
  )

  data.frame(
    evidenceID = rep(NA_character_, n_evidence),
    datasetTaskID = private_submission_chr_vec(datasetTaskID),
    supportingEvidence = private_required_submission_chr_vec(
      evidence_names,
      "supportingEvidence"
    ),
    is_in_data = vapply(
      evidence_names,
      function(evidence_name) {
        private_infer_evidence_in_data(trio$evidence[[evidence_name]], trio$data)
      },
      logical(1)
    ),
    evidenceSourceID = vapply(
      evidence_names,
      function(evidence_name) {
        private_extract_evidence_source_id(trio, evidence_name)
      },
      character(1)
    ),
    evidenceType = private_submission_chr_vec(evidenceType),
    stringsAsFactors = FALSE
  )
}

#' Collect DatasetEvidence submission metadata interactively
#'
#' This helper gathers the evidence-to-task assignment and evidence type for
#' each supporting evidence item in a `Trio`.
#'
#' @param trio A `Trio` object.
#' @param task_args Named list returned by `collectTaskSubmissionInfo()`.
#' @param defaults Optional named list with entries `taskName` and
#'   `evidenceType`. Each entry may be length 1 or length equal to the number of
#'   supporting evidence items in `trio`.
#'
#' @return A named list with `datasetTaskID`, `evidenceName`,
#'   `evidenceType`, and `evidence_task_map`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' task_args <- list(
#'   taskStage = "prediction",
#'   taskType = "classification",
#'   taskName = "class_prediction"
#' )
#' collectEvidenceSubmissionInfo(
#'   trio,
#'   task_args = task_args,
#'   defaults = list(
#'     taskName = "class_prediction",
#'     evidenceType = "experimental_ground_truth"
#'   )
#' )
#' @export
collectEvidenceSubmissionInfo <- function(
    trio,
    task_args,
    defaults = list()
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  if (!is.list(task_args) ||
      is.null(task_args$taskName) ||
      is.null(task_args$taskType)) {
    cli::cli_abort(
      "{.arg task_args} must be a list returned by {.fn collectTaskSubmissionInfo}."
    )
  }

  if (!is.list(defaults)) {
    cli::cli_abort("{.arg defaults} must be a named list.")
  }

  evidence_names <- names(trio$evidence)
  if (length(evidence_names) == 0) {
    cli::cli_abort(
      "The Trio object has no supporting evidence, so no DatasetEvidence information can be collected."
    )
  }

  task_names <- private_required_submission_chr_vec(task_args$taskName, "taskName")
  task_temp_ids <- private_submission_task_ids(length(task_names))

  task_name_default <- private_collect_submission_vector(
    value = defaults$taskName,
    n = length(evidence_names),
    arg = "taskName"
  )
  evidence_type_default <- private_collect_submission_vector(
    value = defaults$evidenceType,
    n = length(evidence_names),
    arg = "evidenceType"
  )

  assigned_task_ids <- character(length(evidence_names))
  assigned_task_names <- character(length(evidence_names))
  evidence_type <- character(length(evidence_names))

  choices <- c(
    "experimental_ground_truth",
    "manual_annotation",
    "reference_based",
    "simulated",
    "derived_proxy",
    "other"
  )

  for (i in seq_along(evidence_names)) {
    evidence_name <- evidence_names[[i]]
    task_name <- private_collect_submission_choice(
      value = task_name_default[[i]],
      choices = task_names,
      title = paste0("Choose task for supporting evidence ", evidence_name)
    )
    assigned_task_names[[i]] <- task_name
    assigned_task_ids[[i]] <- task_temp_ids[match(task_name, task_names)]

    evidence_type[[i]] <- private_collect_submission_choice(
      value = evidence_type_default[[i]],
      choices = choices,
      title = paste0("Choose evidence type for ", evidence_name)
    )
  }

  names(assigned_task_names) <- evidence_names

  missing_tasks <- setdiff(task_names, unique(assigned_task_names))
  if (length(missing_tasks) > 0) {
    cli::cli_abort(c(
      "Each task must have at least one supporting evidence assigned.",
      "i" = "Unassigned task(s): {.val {missing_tasks}}"
    ))
  }

  list(
    datasetTaskID = assigned_task_ids,
    evidenceName = evidence_names,
    evidenceType = evidence_type,
    evidence_task_map = assigned_task_names
  )
}

#' Build Metric submission rows from a Trio object
#'
#' This helper creates one `Metric` row per metric in the Trio object. It does
#' not upload anything and does not modify the existing writeCTD() path.
#'
#' @param trio A `Trio` object.
#'
#' @return A `data.frame` matching the proposed `Metric` table schema.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' buildMetricSubmission(trio)
#' @export
buildMetricSubmission <- function(trio) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  metric_names <- names(trio$metrics)
  if (length(metric_names) == 0) {
    cli::cli_abort(
      "The Trio object has no metrics, so no Metric rows can be created."
    )
  }

  metric_type <- vapply(
    metric_names,
    private_infer_metric_type,
    character(1)
  )

  data.frame(
    metricID = rep(NA_character_, length(metric_names)),
    metricName = metric_names,
    wrapper_r = vapply(
      metric_names,
      function(metric_name) {
        private_metric_wrapper_r(metric_name, metric_type[[metric_name]])
      },
      character(1)
    ),
    metricType = rep(NA_character_, length(metric_names)),
    metricSourceType = metric_type,
    metricKey = vapply(
      metric_names,
      function(metric_name) {
        private_metric_key(
          metric_name = metric_name,
          wrapper_r = private_metric_wrapper_r(metric_name, metric_type[[metric_name]])
        )
      },
      character(1)
    ),
    wrapper_py = rep(NA_character_, length(metric_names)),
    gist_url = rep(NA_character_, length(metric_names)),
    stringsAsFactors = FALSE
  )
}

#' Prepare Trio metric metadata for submission
#'
#' This helper aligns the new submission workflow with the older `writeCTD()`
#' metric handling. Internal package metrics are recorded directly. Custom
#' metrics can optionally be uploaded to a GitHub gist and linked from the
#' resulting `Metric` table rows.
#'
#' @param trio A `Trio` object.
#' @param name Dataset name used for the gist filename. Defaults to `trio$name`.
#' @param uploadCustom Logical; if `TRUE`, custom metrics are uploaded to a
#'   GitHub gist.
#' @param githubPat Optional GitHub personal access token with gist scope.
#' @param gistPublic Logical; whether the created gist should be public.
#'
#' @return A list with entries `Metric`, `gist`, and `custom_metric_lines`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' prepareTrioSubmissionMetrics(trio)
#' @export
prepareTrioSubmissionMetrics <- function(
    trio,
    name = trio$name,
    uploadCustom = FALSE,
    githubPat = NULL,
    gistPublic = TRUE
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  metric_tbl <- buildMetricSubmission(trio)
  metric_names <- metric_tbl$metricName

  custom_metric_lines <- character(0)
  custom_metric_names <- character(0)

  for (metric_name in metric_names) {
    if (!identical(private_infer_metric_type(metric_name), "gist")) {
      next()
    }

    custom_metric_names <- c(custom_metric_names, metric_name)
    custom_metric_lines <- c(
      custom_metric_lines,
      private_submission_metric_lines(trio$metrics[[metric_name]], metric_name)
    )
  }

  gist <- NULL
  if (isTRUE(uploadCustom) && length(custom_metric_lines) > 0) {
    if (is.null(name) || !nzchar(name)) {
      cli::cli_abort(
        "{.arg name} must be provided when uploading custom metrics to a gist."
      )
    }

    gist <- private_submission_create_gist(
      content = custom_metric_lines,
      filename = paste0(name, "_metrics.R"),
      description = paste0("Metrics for Trio ", name),
      public = gistPublic,
      pat = githubPat
    )
  }

  if (length(custom_metric_names) > 0) {
    custom_rows <- metric_tbl$metricName %in% custom_metric_names
    metric_tbl$wrapper_r[custom_rows] <- metric_tbl$metricName[custom_rows]
    metric_tbl$gist_url[custom_rows] <- if (is.null(gist)) {
      NA_character_
    } else {
      gist$html_url
    }
    metric_tbl$metricKey[custom_rows] <- vapply(
      seq_along(metric_tbl$metricName[custom_rows]),
      function(i) {
        private_metric_key(
          metric_name = metric_tbl$metricName[custom_rows][[i]],
          metric_type = metric_tbl$metricSourceType[custom_rows][[i]],
          gist_url = metric_tbl$gist_url[custom_rows][[i]],
          wrapper_r = metric_tbl$wrapper_r[custom_rows][[i]]
        )
      },
      character(1)
    )
  }

  list(
    Metric = metric_tbl,
    gist = gist,
    custom_metric_lines = custom_metric_lines
  )
}

