    cli::cli_abort(
      "A value for {.val {title}} is required in non-interactive mode."
    )
  }

  if (length(choices) == 0) {
    return(private_collect_submission_text(
      prompt = prompt,
      required = TRUE
    ))
  }

  menu_choices <- c(choices, "other")
  selected <- utils::menu(menu_choices, title = title)
  if (selected == 0) {
    cli::cli_abort("A selection for {.val {title}} is required.")
  }

  selected_value <- menu_choices[[selected]]
  if (!identical(selected_value, "other")) {
    return(selected_value)
  }

  private_collect_submission_text(
    prompt = prompt,
    required = TRUE
  )
}

