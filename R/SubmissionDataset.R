#' Build a combined Trio submission object
#'
#' This helper assembles the five Trio-focused submission tables into a single
#' list so it can be inspected locally before any upload step is added.
#'
#' @param trio A `Trio` object.
#' @param dataset_args Named list of arguments passed to
#'   `buildDatasetSubmission()`, excluding `trio`.
#' @param task_args Named list of arguments passed to
#'   `buildDatasetTaskSubmission()`, excluding `trio`.
#' @param evidence_task_map Character vector mapping Trio evidence names to the
#'   corresponding task names in the submission. Names must be evidence names
#'   from `trio$evidence`, values must be task names supplied in `task_args`.
#'
#' @return A named list containing `Dataset`, `DatasetTask`,
#'   `DatasetEvidence`, `Metric`, `DatasetTaskMetric`, and
#'   `submission_links`.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' dataset_args <- list(
#'   dataType = "omics",
#'   dataModality = "transcriptomics",
#'   technology = "RNA-seq",
#'   tissue = "blood",
#'   status = "healthy"
#' )
#' task_args <- list(
#'   taskStage = "prediction",
#'   taskType = "classification",
#'   taskName = "class_prediction"
#' )
#' submission <- buildTrioSubmission(
#'   trio = trio,
#'   dataset_args = dataset_args,
#'   task_args = task_args,
#'   evidence_task_map = c(class_labels = "class_prediction")
#' )
#' names(submission)
#' @export
buildTrioSubmission <- function(
    trio,
    dataset_args,
    task_args,
    evidence_task_map
) {
  if (!inherits(trio, "Trio")) {
    cli::cli_abort("{.arg trio} must be a {.cls Trio} object.")
  }

  if (missing(dataset_args) || !is.list(dataset_args)) {
    cli::cli_abort("{.arg dataset_args} must be a named list.")
  }

  if (missing(task_args) || !is.list(task_args)) {
    cli::cli_abort("{.arg task_args} must be a named list.")
  }

  if (missing(evidence_task_map) || is.null(evidence_task_map)) {
    cli::cli_abort(
      "{.arg evidence_task_map} must map Trio evidence names to submission task names."
    )
  }

  if (is.null(names(evidence_task_map))) {
    cli::cli_abort(
      "{.arg evidence_task_map} must be a named character vector."
    )
  }

  evidence_task_map <- private_required_submission_chr_vec(
    evidence_task_map,
    "evidence_task_map"
  )

  if (!all(names(evidence_task_map) %in% names(trio$evidence))) {
    cli::cli_abort(c(
      "Names of {.arg evidence_task_map} must be Trio evidence names.",
      "i" = "Available evidence: {.val {names(trio$evidence)}}"
    ))
  }

  dataset_tbl <- do.call(
    buildDatasetSubmission,
    c(list(trio = trio), dataset_args)
  )

  task_tbl <- do.call(
    buildDatasetTaskSubmission,
    c(
      list(
        trio = trio,
        datasetID = dataset_tbl$datasetID[[1]]
      ),
      task_args
    )
  )

  task_temp_ids <- private_submission_task_ids(nrow(task_tbl))
  task_lookup <- stats::setNames(task_temp_ids, task_tbl$taskName)

  if (!all(unname(evidence_task_map) %in% task_tbl$taskName)) {
    cli::cli_abort(c(
      "All values of {.arg evidence_task_map} must match a submitted task name.",
      "i" = "Available task names: {.val {task_tbl$taskName}}"
    ))
  }

  ordered_evidence_names <- names(evidence_task_map)
  evidence_task_ids <- unname(task_lookup[evidence_task_map])

  evidence_tbl <- buildDatasetEvidenceSubmission(
    trio,
    datasetTaskID = evidence_task_ids,
    evidenceName = ordered_evidence_names
  )
  evidence_tbl$datasetTaskID <- NA_character_
  metric_tbl <- buildMetricSubmission(trio)
  metric_temp_ids <- private_submission_metric_ids(metric_tbl$metricName)
  task_metric_tbl <- buildDatasetTaskMetricSubmission(
    trio,
    datasetTaskID = task_temp_ids,
    evidenceTaskID = evidence_task_ids,
    evidenceName = ordered_evidence_names
  )
  task_metric_tbl$datasetTaskID <- NA_character_
  task_metric_tbl$metricID <- NA_character_

  list(
    Dataset = dataset_tbl,
    DatasetTask = task_tbl,
    DatasetEvidence = evidence_tbl,
    Metric = metric_tbl,
    DatasetTaskMetric = task_metric_tbl,
    submission_links = list(
      dataset_temp_id = private_submission_dataset_id(),
      task = data.frame(
        task_temp_id = task_temp_ids,
        taskName = task_tbl$taskName,
        stringsAsFactors = FALSE
      ),
      evidence = data.frame(
        evidenceName = ordered_evidence_names,
        task_temp_id = evidence_task_ids,
        stringsAsFactors = FALSE
      ),
      metric = private_build_metric_links(metric_tbl, metric_temp_ids),
      task_metric = private_build_task_metric_links(
        trio = trio,
        evidence_names = ordered_evidence_names,
        evidence_task_ids = evidence_task_ids,
        metric_temp_ids = metric_temp_ids,
        metric_tbl = metric_tbl
      )
    )
  )
}

#' Convert a combined Trio submission to payload structure
#'
#' This helper converts the output of `buildTrioSubmission()` into the nested
#' list structure used by the JSON payload in the prototype submission script.
#'
#' @param submission A submission object returned by `buildTrioSubmission()`.
#'
#' @return A named list with a top-level `payload` entry ready for
#'   `jsonlite::toJSON(..., auto_unbox = TRUE)`.
#' @importFrom jsonlite toJSON
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' submission <- buildTrioSubmission(
#'   trio = trio,
#'   dataset_args = list(
#'     dataType = "omics",
#'     dataModality = "transcriptomics",
#'     technology = "RNA-seq",
#'     tissue = "blood",
#'     status = "healthy"
#'   ),
#'   task_args = list(
#'     taskStage = "prediction",
#'     taskType = "classification",
#'     taskName = "class_prediction"
#'   ),
#'   evidence_task_map = c(class_labels = "class_prediction")
#' )
#' payload <- buildTrioSubmissionPayload(submission)
#' names(payload)
#' @export
buildTrioSubmissionPayload <- function(submission) {
  required_names <- c(
    "Dataset",
    "DatasetTask",
    "DatasetEvidence",
    "Metric",
    "DatasetTaskMetric"
  )

  if (!is.list(submission)) {
    cli::cli_abort("{.arg submission} must be a submission list.")
  }

  missing_names <- setdiff(required_names, names(submission))
  if (length(missing_names) > 0) {
    cli::cli_abort(c(
      "The submission object is missing required tables.",
      "i" = "Missing: {.val {missing_names}}"
    ))
  }

  payload_tables <- list(
    Dataset = private_submission_df_to_records(submission$Dataset),
    DatasetTask = private_submission_df_to_records(submission$DatasetTask),
    DatasetEvidence = private_submission_df_to_records(submission$DatasetEvidence),
    Metric = private_submission_df_to_records(submission$Metric),
    DatasetTaskMetric = private_submission_df_to_records(submission$DatasetTaskMetric)
  )

  payload <- list(payload = payload_tables)

  if (!is.null(submission$submission_links)) {
    payload$submission_links <- list(
      dataset_temp_id = submission$submission_links$dataset_temp_id,
      task = private_submission_df_to_records(submission$submission_links$task),
      evidence = private_submission_df_to_records(submission$submission_links$evidence),
      metric = private_submission_df_to_records(submission$submission_links$metric),
      task_metric = private_submission_df_to_records(submission$submission_links$task_metric)
    )
  }

  payload
}

#' Convert a combined Trio submission to JSON
#'
#' @param submission A submission object returned by `buildTrioSubmission()`.
