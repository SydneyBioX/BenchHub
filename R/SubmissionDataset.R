#' Submit a Trio submission payload to Google Apps Script
#'
#' This helper posts the Trio submission payload to a Google Apps Script
#' endpoint using the same redirect-tolerant approach as the prototype script.
#'
#' @param submission A submission object returned by `buildTrioSubmission()`.
#' @param url Google Apps Script endpoint URL.
#' @param submittedBy Submitter email or identifier.
#' @param submittedType Submission type label. Defaults to `"Trio"`.
#'
#' @return A list containing request status information and response text.
#' @examples
#' data <- data.frame(feature = c(1, 2, 3), row.names = paste0("sample", 1:3))
#' labels <- factor(c("A", "B", "A"))
#' names(labels) <- rownames(data)
#' trio <- Trio$new(
#'   data = data,
#'   evidence = list(class_labels = list(
#'     evidence = labels,
#'     metrics = "macroF1Metric"
#'   )),
#'   metrics = list(macroF1Metric = macroF1Metric),
#'   name = "example_dataset",
#'   description = "A small example dataset."
#' )
#' submission <- buildTrioSubmission(
#'   trio = trio,
#'   dataset_args = list(
#'     dataType = "omics",
#'     dataModality = "transcriptomics",
#'     technology = "RNA-seq",
#'     tissue = "blood",
#'     status = "healthy"
#'   ),
#'   task_args = list(
#'     taskStage = "prediction",
#'     taskType = "classification",
#'     taskName = "class_prediction"
#'   ),
#'   evidence_task_map = c(class_labels = "class_prediction")
#' )
#'
#' if (interactive() && curl::has_internet()) {
#'   response <- submitTrioSubmission(
#'     submission,
#'     url = "https://script.google.com/macros/s/example/exec",
#'     submittedBy = "researcher@example.org"
#'   )
#'   names(response)
#' }
#' @export
submitTrioSubmission <- function(
    submission,
    url,
    submittedBy,
    submittedType = "Trio"
) {
  if (!curl::has_internet()) {
    cli::cli_abort("No internet connection available.")
  }

  if (missing(url) || is.null(url) || !is.character(url) ||
      length(url) != 1 || is.na(url) || !nzchar(url)) {
    cli::cli_abort(
      "{.arg url} must be a single non-empty character string."
    )
  }

  if (missing(submittedBy) || is.null(submittedBy) ||
      !is.character(submittedBy) || length(submittedBy) != 1 ||
      is.na(submittedBy) || !nzchar(submittedBy)) {
    cli::cli_abort(
      "{.arg submittedBy} must be a single non-empty character string."
    )
  }

  if (missing(submittedType) || is.null(submittedType) ||
      !is.character(submittedType) || length(submittedType) != 1 ||
      is.na(submittedType) || !nzchar(submittedType)) {
    cli::cli_abort(
      "{.arg submittedType} must be a single non-empty character string."
    )
  }

  payload <- buildTrioSubmissionPayload(submission = submission)

  body <- list(
    submittedBy = submittedBy,
    submittedType = submittedType,
    payload = payload
  )

  resp1 <- httr2::request(url) |>
    httr2::req_method("POST") |>
    httr2::req_headers(`Content-Type` = "application/json") |>
    httr2::req_body_json(body, auto_unbox = TRUE) |>
    httr2::req_options(followlocation = FALSE) |>
    httr2::req_error(is_error = function(resp) FALSE) |>
    httr2::req_perform()

  status1 <- httr2::resp_status(resp1)
  headers1 <- httr2::resp_headers(resp1)

  if (status1 %in% c(301, 302, 303, 307, 308) &&
      !is.null(headers1[["location"]])) {
    resp2 <- httr2::request(headers1[["location"]]) |>
      httr2::req_method("GET") |>
      httr2::req_error(is_error = function(resp) FALSE) |>
      httr2::req_perform()

    return(list(
      ok = httr2::resp_status(resp2) == 200,
      post_status = status1,
      final_status = httr2::resp_status(resp2),
      final_body = httr2::resp_body_string(resp2)
    ))
  }

  list(
    ok = status1 == 200,
    post_status = status1,
    final_status = status1,
    final_body = httr2::resp_body_string(resp1)
  )
}

private_validate_submission_choice <- function(value, arg, choices) {
  if (missing(value) || is.null(value) || length(value) != 1 || !nzchar(value)) {
    cli::cli_abort(
      "The {.arg {arg}} argument must be a single non-empty string."
    )
  }

  if (!value %in% choices) {
    cli::cli_abort(c(
      "Invalid value for {.arg {arg}}.",
      "i" = "Choose one of: {.val {choices}}"
    ))
  }
}

private_get_submission_num_samples <- function(data) {
  if (is.null(data)) {
    return(NA_integer_)
  }

  if (inherits(data, "SingleCellExperiment")) {
    return(as.integer(ncol(data)))
  }

  if (isTabular(data) && !is.null(nrow(data))) {
    return(as.integer(nrow(data)))
  }

  dims <- dim(data)
  if (!is.null(dims) && length(dims) >= 1) {
    return(as.integer(dims[[1]]))
  }

  NA_integer_
}

private_submission_chr <- function(x) {
  if (is.null(x) || length(x) == 0 || is.na(x) || !nzchar(as.character(x))) {
    return(NA_character_)
  }

  as.character(x)
}

private_submission_chr_vec <- function(x) {
  x_chr <- as.character(x)
  x_chr[is.na(x_chr) | !nzchar(x_chr)] <- NA_character_
  x_chr
}

private_recycle_submission_value <- function(value, n, arg) {
  if (missing(value) || is.null(value) || length(value) == 0) {
    cli::cli_abort(
      "The {.arg {arg}} argument must be provided."
    )
  }

  if (length(value) == 1) {
    return(rep(value, n))
  }

  if (length(value) != n) {
    cli::cli_abort(c(
      "Invalid length for {.arg {arg}}.",
      "i" = "Provide either one value or exactly {.val {n}} values."
    ))
  }

  value
}

private_submission_row_count <- function(...) {
  lengths <- vapply(list(...), length, integer(1))
  lengths <- lengths[lengths > 0]

  if (length(lengths) == 0) {
    cli::cli_abort("At least one submission field must be provided.")
  }

  max(lengths)
}

private_required_submission_chr_vec <- function(x, arg) {
  x_chr <- as.character(x)
  names(x_chr) <- names(x)

  if (any(is.na(x_chr) | !nzchar(x_chr))) {
    cli::cli_abort(
      "All values in {.arg {arg}} must be non-empty strings."
    )
  }

  x_chr
}

private_infer_evidence_in_data <- function(one_evidence, data) {
  evidence_data <- one_evidence$evidence

  if (is.function(evidence_data)) {
    return(TRUE)
  }

  if (isTabular(evidence_data)) {
    return(identical(rownames(evidence_data), rownames(data)))
  }

  if (!is.null(names(evidence_data)) && !is.null(rownames(data))) {
    return(identical(names(evidence_data), rownames(data)))
  }

  FALSE
}

private_extract_evidence_source_id <- function(trio, evidence_name) {
