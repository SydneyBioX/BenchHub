private_prompt_with_default <- function(prompt, default = NULL, required = TRUE) {
  default_chr <- private_submission_chr(default)

  if (!interactive()) {
    if (!is.na(default_chr) || !required) {
      return(default_chr)
    }
    cli::cli_abort(
      "A value for {.val {prompt}} is required in non-interactive mode."
    )
  }

  prompt_text <- if (!is.na(default_chr)) {
    paste0(prompt, " [", default_chr, "]: ")
  } else {
    paste0(prompt, ": ")
  }

  entered <- readline(prompt_text)
  entered_chr <- private_submission_chr(entered)

  if (is.na(entered_chr)) {
    if (!is.na(default_chr)) {
      return(default_chr)
    }
    if (!required) {
      return(NA_character_)
    }
    cli::cli_abort("A value for {.val {prompt}} is required.")
  }

  entered_chr
}

