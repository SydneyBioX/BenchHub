private_verify_submission_figshare <- function(
    trio,
    prepared,
    figshareUrl,
    datasetFileName = NULL,
    evidenceFileName = NULL,
    skipMd5Check = FALSE
) {
  if (missing(figshareUrl) || is.null(figshareUrl) || !nzchar(figshareUrl)) {
    cli::cli_abort("{.arg figshareUrl} must be provided when verifying Figshare upload.")
  }

  if (!grepl("figshare", figshareUrl, ignore.case = TRUE)) {
    cli::cli_abort("{.arg figshareUrl} must be a Figshare URL.")
  }

  article_id <- stringr::str_extract(figshareUrl, "(?<=/)[0-9]+")
  if (is.na(article_id) || !nzchar(article_id)) {
    cli::cli_abort("Could not extract a Figshare article ID from {.arg figshareUrl}.")
  }

  file_df <- figshareListFiles(article_id)
  if (nrow(file_df) == 0) {
    cli::cli_abort("No files were found in the Figshare article.")
  }

  dataset_match <- NULL
  if (isTRUE(prepared$dataset$prepared)) {
    dataset_match <- private_match_submission_figshare_file(
      available = file_df,
      preferred = datasetFileName,
      default_name = prepared$dataset$fileName,
      suffix = "_dataset.rds"
    )
  }

  evidence_match <- NULL
  if (isTRUE(prepared$evidence$prepared)) {
    evidence_match <- private_match_submission_figshare_file(
      available = file_df,
      preferred = evidenceFileName,
      default_name = prepared$evidence$fileName,
      suffix = "_evidence.rds"
    )
  }

  dataset_md5_ok <- NA
  if (!is.null(dataset_match)) {
    dataset_md5_ok <- !is.na(prepared$dataset$md5) &&
      identical(unname(file_df$computed_md5[dataset_match$row]), prepared$dataset$md5)
  }

  if (isTRUE(prepared$dataset$prepared) && !dataset_md5_ok && !skipMd5Check) {
    cli::cli_abort("Uploaded dataset file MD5 does not match the prepared dataset file.")
  }

  evidence_md5_ok <- NA
  if (!is.null(evidence_match)) {
    evidence_md5_ok <- !is.na(prepared$evidence$md5) &&
      identical(unname(file_df$computed_md5[evidence_match$row]), prepared$evidence$md5)
    if (!evidence_md5_ok && !skipMd5Check) {
      cli::cli_abort("Uploaded evidence file MD5 does not match the prepared evidence file.")
    }
  }

  list(
    article_id = article_id,
    dataset = if (is.null(dataset_match)) {
      NULL
    } else {
      list(
        fileName = dataset_match$file_name,
        fileID = as.character(file_df$id[dataset_match$row]),
        source = "figshare",
        sourceID = paste0(article_id, "/", file_df$id[dataset_match$row]),
        md5_ok = dataset_md5_ok
      )
    },
    evidence = if (is.null(evidence_match)) {
      NULL
    } else {
      list(
        fileName = evidence_match$file_name,
        fileID = as.character(file_df$id[evidence_match$row]),
        source = "figshare",
        sourceID = paste0(article_id, "/", file_df$id[evidence_match$row]),
        md5_ok = evidence_md5_ok
      )
    }
  )
}

private_match_submission_figshare_file <- function(
    available,
    preferred = NULL,
    default_name = NULL,
    suffix
) {
  file_names <- available$name

  candidates <- c(preferred, default_name)
  candidates <- candidates[!is.na(candidates) & nzchar(candidates)]

  for (candidate in candidates) {
    idx <- which(file_names == candidate)
    if (length(idx) > 0) {
      return(list(row = idx[[1]], file_name = file_names[[idx[[1]]]]))
    }
  }

  suffix_idx <- which(endsWith(tolower(file_names), tolower(suffix)))
  if (length(suffix_idx) > 0) {
    idx <- suffix_idx[[1]]
    return(list(row = idx, file_name = file_names[[idx]]))
  }

  cli::cli_abort(c(
    "Could not find the expected uploaded file in the Figshare article.",
    "i" = "Available files: {.val {file_names}}"
  ))
}

private_submission_metric_lines <- function(metric_fn, metric_name) {
  metric_env <- environment(metric_fn)

  if (!is.null(metric_env) &&
      exists("metric", envir = metric_env, inherits = FALSE)) {
    metric <- get("metric", envir = metric_env, inherits = FALSE)
    args <- if (exists("args", envir = metric_env, inherits = FALSE)) {
      get("args", envir = metric_env, inherits = FALSE)
    } else {
      NULL
    }
  } else {
    metric <- metric_fn
    args <- NULL
  }

  metric_deparsed <- deparse(metric)
  metric_deparsed[1] <- paste0(metric_name, " <- ", metric_deparsed[1])
  args_deparsed <- paste0(metric_name, "Args <- ", deparse(args))

  c(metric_deparsed, args_deparsed)
}

